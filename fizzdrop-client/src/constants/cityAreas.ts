/**
 * Returns available areas for a city. If no predefined list, returns standard municipal sectors.
 */
export function getAvailableAreasForCity(cityName: string): string[] {
  if (!cityName) return ['Central Hub', 'North Zone', 'South Zone'];
  const trimmed = cityName.trim();
  if (CITY_AREAS_MAP[trimmed]) {
    return CITY_AREAS_MAP[trimmed];
  }
  // Case-insensitive lookup
  const matchKey = Object.keys(CITY_AREAS_MAP).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (matchKey && CITY_AREAS_MAP[matchKey]) {
    return CITY_AREAS_MAP[matchKey];
  }
  return [
    `${trimmed} Sadar Commercial Hub`,
    `${trimmed} North Zone`,
    `${trimmed} South Depot Area`,
    `${trimmed} Industrial Area`,
    `${trimmed} Station Road`,
  ];
}

/**
 * Parses allocated_areas string into a map of CityName -> AreaNames[]
 */
export function parseAllocatedAreas(raw: string | undefined | null): Record<string, string[]> {
  if (!raw || typeof raw !== 'string' || !raw.trim()) {
    return {};
  }
  try {
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
      const result: Record<string, string[]> = {};
      for (const [key, val] of Object.entries(parsed)) {
        if (Array.isArray(val)) {
          result[key] = val.map((x) => String(x).trim()).filter(Boolean);
        } else if (typeof val === 'string' && val.trim()) {
          result[key] = [val.trim()];
        }
      }
      return result;
    }
  } catch {
    // If simple text or comma list
    const parts = raw.split(',').map((p) => p.trim()).filter(Boolean);
    if (parts.length > 0) {
      return { General: parts };
    }
  }
  return {};
}

/**
 * Serializes allocated areas map into JSON string
 */
export function serializeAllocatedAreas(map: Record<string, string[]>): string {
  const cleanMap: Record<string, string[]> = {};
  for (const [city, areas] of Object.entries(map)) {
    if (Array.isArray(areas) && areas.length > 0) {
      cleanMap[city] = Array.from(new Set(areas));
    }
  }
  return JSON.stringify(cleanMap);
}
